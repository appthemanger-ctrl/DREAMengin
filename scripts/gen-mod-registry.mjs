
import fs from 'node:fs';
import path from 'node:path';

const MOD_DIR = path.join(process.cwd(), 'modules');
const OUT = path.join(process.cwd(), 'lib', 'modules', 'registry.gen.ts');

function findModules() {
  if (!fs.existsSync(MOD_DIR)) return [];
  const entries = fs.readdirSync(MOD_DIR, { withFileTypes: true });
  const mods = [];
  for (const e of entries) {
    if (!e.isDirectory()) continue;
    const dir = path.join(MOD_DIR, e.name);
    const manifestPath = path.join(dir, 'module.json');
    if (!fs.existsSync(manifestPath)) continue;
    try {
      const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf-8'));
      mods.push({ name: e.name, dir, manifest });
    } catch {}
  }
  return mods;
}

const mods = findModules();
let imports = '';
let widgets = [];
let connectors = [];

for (const m of mods) {
  if (m.manifest.type === 'widget') {
    const id = `W_${m.name.replace(/[^a-z0-9_]/gi,'_')}`;
    const entry = './' + path.relative(path.join(process.cwd(),'lib','modules'), path.join(m.dir, m.manifest.entry)).replace(/\\/g,'/');
    imports += `import ${id} from '${entry}';\n`;
    widgets.push(`{ name: '${m.manifest.name || m.name}', slug: '${m.name}', Component: ${id} }`);
  }
  if (m.manifest.type === 'connector') {
    const id = `C_${m.name.replace(/[^a-z0-9_]/gi,'_')}`;
    const entry = './' + path.relative(path.join(process.cwd(),'lib','modules'), path.join(m.dir, m.manifest.entry)).replace(/\\/g,'/');
    imports += `import * as ${id} from '${entry}';\n`;
    connectors.push(`{ name: '${m.manifest.name || m.name}', slug: '${m.name}', impl: ${id} }`);
  }
}

const out = `// AUTO-GENERATED by scripts/gen-mod-registry.mjs
${imports}
export const widgetModules = [${widgets.join(',')}];
export const connectorModules = [${connectors.join(',')}];
`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, out);
console.log('Generated', OUT, 'with', widgetModules?.length ?? widgets.length, 'widgets and', connectorModules?.length ?? connectors.length, 'connectors');
